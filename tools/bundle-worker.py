#!/usr/bin/env python3
"""Inline the Worker's one import into a single pasteable file.

The Worker imports the proofreading contract from src/shared/proofread.js so
there is only ever one copy of the prompt. Wrangler bundles that at deploy
time, but the Cloudflare dashboard's editor has no bundler - it takes one file.
This writes that file, so deploying needs no Node and no tooling at all.

    python3 tools/bundle-worker.py
"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

shared = open(os.path.join(ROOT, "src/shared/proofread.js"), encoding="utf8").read()
worker = open(os.path.join(ROOT, "worker/src/index.js"), encoding="utf8").read()

# Strip the shared file's own export keywords: everything lands in one scope.
shared = re.sub(r"^export \{[^}]*\};\s*$", "", shared, flags=re.M)
shared = re.sub(r"^export (const|function) ", r"\1 ", shared, flags=re.M)

# Drop the import line from the worker.
worker = re.sub(r"^import \{[^}]*\} from '\.\./\.\./src/shared/proofread\.js';\s*$",
                "", worker, flags=re.M)

banner = """// Caret Worker - SINGLE FILE BUILD. Do not edit this one.
//
// Generated by tools/bundle-worker.py from worker/src/index.js and
// src/shared/proofread.js. Edit those and run the script again.
//
// This exists so the Worker can be deployed by pasting it into the Cloudflare
// dashboard's editor, with no Node and no wrangler. After pasting, the Worker
// still needs its two bindings adding under Settings:
//
//   Workers AI  ->  variable name  AI
//   KV namespace ->  variable name  KEYS
//
// and, optionally, two plain text variables:
//
//   MODEL           @cf/meta/llama-3.1-8b-instruct
//   PER_KEY_DAILY   120

"""

out = banner + shared.strip() + "\n\n" + worker.strip() + "\n"
path = os.path.join(ROOT, "worker/dist/worker.js")
with open(path, "w", encoding="utf8") as f:
    f.write(out)
print(f"wrote {path} ({len(out.splitlines())} lines, {len(out)} bytes)")
